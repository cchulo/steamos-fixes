# components/update.sh — SteamOS A/B update survival (plan §4).
#
# Owns:
#   * the boot service  /etc/systemd/system/steamos-fixes.service
#     (+ multi-user.target.wants link) — re-applies what an update dropped;
#   * the user notifier /etc/systemd/user/steamos-fixes-notify.service
#     (+ default.target.wants link);
#   * the RAUC handlers  /var/lib/steamos-fixes/libexec/rauc-{pre,post}-install.hook
#     and their registration in /etc/rauc/system.conf (documented exception,
#     lib/rauc.sh);
#   * the SteamOS keep list /etc/atomic-update.conf.d/steamos-fixes.conf:
#     an atomic update prunes /etc to the paths listed in
#     /usr/lib/rauc/atomic-update-keep.conf and /etc/atomic-update.conf.d/*.conf
#     (holo-sync-var, steamos-customizations 3.9), so every /etc path we own
#     is listed there, generated from our naming conventions plus any manifest
#     path they do not cover (docs/update-survival.md);
#   * reconciling the booted slot's boot entry with the desired state that
#     other components declare through slots_desired_set (documented
#     exception, lib/slots.sh);
#   * the factory-reset fail-safe that undoes that boot entry change when
#     nothing else of ours is left: uninstall/efi-cleanup.sh copied to
#     /efi/EFI/steamos/steamos-fixes-cleanup.sh on the slot whose entry
#     we reconcile (the booted slot here, the new slot when the RAUC
#     post-install handler runs `apply --slot`), and the shutdown hook
#     /etc/systemd/system/steamos-fixes-reset-cleanup.service (+ its
#     multi-user.target.wants link) that runs it on both slots when a
#     factory reset is pending.
# The enable links are created through manifest_install_symlink, not
# `systemctl enable`, so uninstall removes exactly what we added.

# shellcheck source=lib/rauc.sh
. "$SOF_SRC/lib/rauc.sh"
# shellcheck source=lib/slots.sh
. "$SOF_SRC/lib/slots.sh"

# shellcheck disable=SC2034  # read by lib/component.sh
COMPONENT_DESCRIPTION="survive SteamOS updates: RAUC pre/post-install handlers, boot re-apply service, notifier"

UPDATE_UNIT="${SOF_NAME}.service"
UPDATE_NOTIFY_UNIT="${SOF_NAME}-notify.service"
UPDATE_RESET_UNIT="${SOF_NAME}-reset-cleanup.service"
UPDATE_CLEANUP_SRC="uninstall/efi-cleanup.sh"
UPDATE_CLEANUP_REL="${SLOTS_GRUB_DIR_REL}/${SOF_NAME}-cleanup.sh"
UPDATE_KEEP_REL="/etc/atomic-update.conf.d/${SOF_NAME}.conf"

# update_keep_patterns : the keep-list globs that cover our naming
# conventions ('*' matches within one path component, '**' across them).
# /etc/systemd/system units and their .wants links are on SteamOS's own
# list; /etc/rauc/system.conf is deliberately not kept (it must follow
# Valve's version; the RAUC block is re-added by the post-install handler).
update_keep_patterns() {
    printf '%s\n' \
        "${SOF_EARLY_REL}/**" \
        "/etc/modprobe.d/${SOF_NAME}-*.conf" \
        "/etc/default/grub.d/${SOF_NAME}-*.cfg" \
        "/etc/systemd/user/${SOF_NAME}-*.service" \
        "/etc/systemd/user/*.wants/${SOF_NAME}-*.service"
}

# _update_keep_regex <glob> : the glob as an anchored extended regex.
_update_keep_regex() {
    printf '^%s$\n' "$1" | sed -e 's/[.]/\\./g' -e 's/\*\*/\\001/g' -e 's/\*/[^\/]*/g' -e 's/\\001/.*/g'
}

# _update_keep_all_patterns : ours plus the entries of SteamOS's own keep
# list that our units rely on.
_update_keep_all_patterns() {
    update_keep_patterns
    printf '%s\n' '/etc/systemd/system/*.service' '/etc/systemd/system/*.wants/**' '/etc/systemd/system/*.service.d/**'
}

# update_keep_uncovered : manifest paths under /etc that no pattern covers
# (excluding /etc/rauc and the keep list itself), one per line. Patterns
# and paths are read line by line, never word-split: an unquoted
# "/etc/systemd/system/*.service" would be expanded by the shell against
# the host's real /etc (it was, on a Linux CI runner).
update_keep_uncovered() {
    local p g re covered
    {
        manifest_entries | _manifest_select kind file | _manifest_field path
        manifest_entries | _manifest_select kind symlink | _manifest_field path
    } | while IFS= read -r p; do
        case "$p" in
            /etc/rauc/* | "$UPDATE_KEEP_REL") continue ;;
            /etc/*) ;;
            *) continue ;;
        esac
        covered=0
        while IFS= read -r g; do
            [ -n "$g" ] || continue
            re=$(_update_keep_regex "$g")
            if printf '%s\n' "$p" | grep -Eq -- "$re"; then
                covered=1
                break
            fi
        done <<EOF
$(_update_keep_all_patterns)
EOF
        [ "$covered" = 1 ] || printf '%s\n' "$p"
    done | sort -u
}

# update_render_keep_list : the drop-in on stdout.
update_render_keep_list() {
    printf '## Generated by %s (component update); do not edit, run "%s apply".\n' "$SOF_NAME" "$SOF_NAME"
    printf '## Paths SteamOS keeps in /etc across an atomic update (holo-sync-var\n'
    printf '## prunes everything not listed here or in atomic-update-keep.conf).\n'
    update_keep_patterns
    update_keep_uncovered
}

# _update_keep_current : the installed keep list is what we would render.
_update_keep_current() {
    local f
    f=$(sof_path "$UPDATE_KEEP_REL")
    [ -f "$f" ] || return 1
    [ "$(cat "$f")" = "$(update_render_keep_list)" ]
}

# update_keep_install : (re)write the keep list through the manifest.
update_keep_install() {
    local tmp
    tmp=$(mktemp "${TMPDIR:-/tmp}/sof-keep.XXXXXX") || return 1
    update_render_keep_list >"$tmp"
    manifest_install_file "$tmp" "$UPDATE_KEEP_REL" update 0644 shared
    rm -f "$tmp"
}

update_files() {
    printf 'systemd/%s\t/etc/systemd/system/%s\t0644\n' "$UPDATE_UNIT" "$UPDATE_UNIT"
    printf 'systemd/%s\t/etc/systemd/user/%s\t0644\n' "$UPDATE_NOTIFY_UNIT" "$UPDATE_NOTIFY_UNIT"
    printf 'systemd/%s\t/etc/systemd/system/%s\t0644\n' "$UPDATE_RESET_UNIT" "$UPDATE_RESET_UNIT"
    printf 'rauc/pre-install.hook\t%s\t0755\n' "$RAUC_PRE_HANDLER_REL"
    printf 'rauc/post-install.hook\t%s\t0755\n' "$RAUC_POST_HANDLER_REL"
}

update_apply() {
    local slot
    manifest_install_symlink "../$UPDATE_UNIT" \
        "/etc/systemd/system/multi-user.target.wants/$UPDATE_UNIT" update
    manifest_install_symlink "../$UPDATE_NOTIFY_UNIT" \
        "/etc/systemd/user/default.target.wants/$UPDATE_NOTIFY_UNIT" update
    manifest_install_symlink "../$UPDATE_RESET_UNIT" \
        "/etc/systemd/system/multi-user.target.wants/$UPDATE_RESET_UNIT" update
    update_cleanup_install
    update_keep_install
    rauc_register "$RAUC_PRE_HANDLER_REL" "$RAUC_POST_HANDLER_REL"
    if slot=$(slots_active 2>/dev/null); then
        slots_entry_reconcile "$slot"
    else
        log_debug "update: active slot unknown; boot entry left alone"
    fi
    if [ -z "$SOF_ROOT" ] && [ "$SOF_DRY_RUN" != 1 ] && sof_have systemctl; then
        systemctl daemon-reload >/dev/null 2>&1 || true
        # Arm the shutdown hook now, not only from the next boot on.
        systemctl start --no-block "$UPDATE_RESET_UNIT" >/dev/null 2>&1 || true
    fi
    return 0
}

# update_cleanup_install : the EFI clean-up script lives next to the
# grub.cfg it restores, on the efi partition of the slot being applied
# (vfat: no exec bit, it is run as `sh <path>`). Only where that directory
# exists, i.e. where lib/slots.sh can modify a grub entry; never created.
update_cleanup_install() {
    local real
    if ! [ -d "$(sof_path "$SLOTS_GRUB_DIR_REL")" ]; then
        log_debug "update: no $SLOTS_GRUB_DIR_REL; EFI clean-up script not installed"
        return 0
    fi
    real=$(sof_path "$UPDATE_CLEANUP_REL")
    if [ -f "$real" ] && ! [ -L "$real" ] && ! manifest_has "$UPDATE_CLEANUP_REL" \
        && grep -q "^# $SOF_NAME EFI clean-up" "$real" 2>/dev/null; then
        # A copy left by an earlier install whose manifest is gone (e.g. this
        # slot's efi kept it through an uninstall run from the other slot).
        log_info "update: replacing a leftover $UPDATE_CLEANUP_REL from an earlier install"
        if [ "$SOF_DRY_RUN" = 1 ]; then
            printf '[dry-run] replace %s\n' "$real" >&2
            return 0
        fi
        rm -f "$real"
    fi
    manifest_install_file "$SOF_SRC/$UPDATE_CLEANUP_SRC" "$UPDATE_CLEANUP_REL" update 0644 esp
}

# Never superseded: this is our own re-apply machinery, there is no stock
# SteamOS feature that could replace it. (Retire it together with the last
# other component.)
update_probe() {
    return "$PROBE_NO"
}

# Default status, plus the two things the manifest cannot see: our RAUC
# block (a SteamOS update gives the new slot a stock system.conf) and the
# boot entry (regenerated by steamos-finalize-install on update).
update_status() {
    local st slot
    st=$(component_default_status update)
    if [ "$st" = active ]; then
        _update_keep_current || st=stock
        rauc_registered "$RAUC_PRE_HANDLER_REL" "$RAUC_POST_HANDLER_REL" || st=stock
        if slot=$(slots_active 2>/dev/null) && ! slots_entry_in_sync "$slot"; then
            st=stock
        fi
    fi
    printf '%s\n' "$st"
}

# update_status_detail : why the status is what it is.
update_status_detail() {
    local slot
    if ! manifest_has "$UPDATE_KEEP_REL"; then
        printf 'not installed\n'
    elif ! _update_keep_current; then
        printf 'the SteamOS keep list is out of date with the installed files (run: %s apply --only update)\n' "$SOF_NAME"
    elif ! rauc_registered "$RAUC_PRE_HANDLER_REL" "$RAUC_POST_HANDLER_REL"; then
        printf 'RAUC handlers not registered in /etc/rauc/system.conf\n'
    elif slot=$(slots_active 2>/dev/null) && ! slots_entry_in_sync "$slot"; then
        printf 'boot entry of slot %s is not in sync\n' "$slot"
    else
        printf 'RAUC handlers, keep list, boot service and boot entry in place\n'
    fi
}

update_remove() {
    local slot
    rauc_unregister
    if slot=$(slots_active 2>/dev/null); then
        slots_entry_restore "$slot"
    fi
    # Disarm the shutdown hook before its files go (live system only;
    # stopping it runs the clean-up only if a factory reset is pending).
    if [ -z "$SOF_ROOT" ] && [ "$SOF_DRY_RUN" != 1 ] && sof_have systemctl; then
        systemctl stop "$UPDATE_RESET_UNIT" >/dev/null 2>&1 || true
    fi
    # The units, their enable links and the EFI clean-up script are
    # manifest entries; uninstall removes them and runs daemon-reload
    # afterwards.
    return 0
}
